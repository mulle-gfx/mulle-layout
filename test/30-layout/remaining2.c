#include <mulle-layout/mulle-layout.h>

#include <stdio.h>


static void   test( CGRect layoutRect,
                    struct MulleEdgeInsets layoutInsets,
                    CGSize size1,
                    struct  MulleEdgeInsets insets1,
                    CGSize size2,
                    struct  MulleEdgeInsets insets2)
{
   struct MulleLayout  layout;
   CGRect              part;
   CGRect              remainderRect;
   CGSize              remainderSize;
   CGPoint             remainderPoint;

   MulleLayoutInit( &layout, layoutRect, layoutInsets);

   part = MulleLayoutAddToRow( &layout, size1, insets1);

   fprintf( stdout, "[ %g %g %g %g ]",
                     part.origin.x,
                     part.origin.y,
                     part.size.width,
                     part.size.height);

   part = MulleLayoutAddToRow( &layout, size2, insets2);

   fprintf( stdout, " [ %g %g %g %g ]",
                     part.origin.x,
                     part.origin.y,
                     part.size.width,
                     part.size.height);


   remainderPoint = MulleLayoutGetRemainingRowContentOrigin( &layout);
   fprintf( stdout, " (p: %g %g)",
                     remainderPoint.x,
                     remainderPoint.y);

   remainderSize = MulleLayoutGetRemainingRowContentSize( &layout);
   fprintf( stdout, " (s: %g %g)",
                     remainderSize.width,
                     remainderSize.height);

   remainderRect = MulleLayoutGetRemainingRowContentRect( &layout);
   fprintf( stdout, " (r: %g %g %g %g)\n",
                     remainderRect.origin.x,
                     remainderRect.origin.y,
                     remainderRect.size.width,
                     remainderRect.size.height);
   MulleLayoutDone( &layout);
}



int   main( int argc, char *argv[])
{
   test( CGRectMake( 100, 100, 300, 200), MulleEdgeInsetsMake( 10, 15, 20, 25),
         CGSizeMake( 50, 50), MulleEdgeInsetsMake( 7, 14, 21, 28),
         CGSizeMake( 50, 50), MulleEdgeInsetsMake( 7, 14, 21, 28));

   test( CGRectMake( 100, 100, 300, 200), MulleEdgeInsetsMake( 10, 15, 20, 25),
         CGSizeMake( 50, 50), MulleEdgeInsetsMake( 7, 14, 21, 28),
         CGSizeMake( 50, 50), MulleEdgeInsetsMake( 20, 32, 0, 16));

   return( 0);
}




