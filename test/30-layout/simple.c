#include <mulle-layout/mulle-layout.h>

#include <stdio.h>


static void   test( CGRect layoutRect,
                    CGSize size1,
                    CGSize size2)
{
   struct MulleLayout  layout;
   CGRect              part;
   CGSize              remainder;
   CGSize              content;

   MulleLayoutInit( &layout, layoutRect, MulleEdgeInsetsZero);

   part = MulleLayoutAddToRow( &layout,
                               size1,
                               MulleEdgeInsetsZero);
   fprintf( stdout, "%g %g\n", layoutRect.size.width, layoutRect.size.height);

//   content   = MulleLayoutGetRowContentSize( &layout);
//   fprintf( stdout, "%g %g\n", content.width, content.height);
   remainder = MulleLayoutGetRemainingRowContentSize( &layout);
   fprintf( stdout, "%g %g\n", remainder.width, remainder.height);

   part = MulleLayoutAddToRow( &layout,
                               size2,
                               MulleEdgeInsetsZero);
//   content   = MulleLayoutGetRowContentSize( &layout);
//   fprintf( stdout, "%g %g\n", content.width, content.height);
   remainder = MulleLayoutGetRemainingRowContentSize( &layout);
   fprintf( stdout, "%g %g\n", remainder.width, remainder.height);

   MulleLayoutDone( &layout);
}




int   main()
{
   test( CGRectMake( 0, 0, 100, 20), 
         CGSizeMake( 10, 10),
         CGSizeMake( 10, 15));

   return( 0);
}




