static unsigned int    row_values[] =
{
   0
};

#define array_count( array)  (sizeof( array) / sizeof( array[ 0]))

int   main()
{
   int                i;
   int                j;
   int                k;
   int                l;
   int                m;
   int                n;
   CGSize             size;
   unsigned int       rows;
   unsigned int       cols;
   struct MulleGrid   grid;
   CGRect             canvas;
   int                rval;
   int                closest;
   int                closest_rows = -1;
   int                closest_columns = -1;
   CGFloat            area;

   closest = 1024 * 768;
   for( cols = 1; cols < 100; cols++)
      for( rows = 1; rows < 100; rows++)
      {
         if( cols * rows < 1024)
            continue;

         canvas = CGRectMake( 0, 0, 1024, 768);
         MulleGridInit( &grid,
                        canvas,
                        MulleEdgeInsetsZero,
                        CGSizeMake( 0, 0),
                        rows,
                        cols,
                        CGSizeMake( 10, 10));
         rval = MulleGridConstruct( &grid, 1024, NULL);
         if( MulleGridIsValid( &grid))
         {
            mulle_printf( "row/column: %u,%u ", rows, cols);
            mulle_printf( "==> itemSize:%g,%g itemAspect:%g itemArea:%g rows/columns:%u/%u area:%g",
                              grid.itemSize.width, grid.itemSize.height,
                              grid.itemSize.width / grid.itemSize.height,
                              grid.itemSize.width * grid.itemSize.height,
                              grid.rows,
                              grid.columns,
                              1024 * grid.itemSize.width * grid.itemSize.height);
            mulle_printf( "\n");

            // do after print :)
            assert( rval == 1);

            area = (1024 * 768) - (grid.itemSize.width * grid.itemSize.height * 1024);
            if( area < closest)
            {
               closest_rows    = rows;
               closest_columns = cols;
               closest         = area;
            }
         }
         else
            assert( rval == 0);
      }

   mulle_printf( "closest: %d,%d\n", closest_rows, closest_columns);
   return( 0);
}




